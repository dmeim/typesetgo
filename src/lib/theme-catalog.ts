// Format theme name for display (capitalize first letter of each word)
export const formatThemeName = (name: string): string => {
  // Check for override first
  if (THEME_DISPLAY_NAMES[name]) {
    return THEME_DISPLAY_NAMES[name];
  }

  // Default: capitalize first letter of each word
  return name
    .split(/[-_]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
};


/** Shared by Vite and the isolated browser fixture; no palettes enter the index. */
export function createThemeCatalogEntry(id: string, source: unknown): ThemeCatalogEntry {
  const record = (value: unknown): Record<string, unknown> => {
    if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error(`Invalid theme metadata: ${id}`);
    return value as Record<string, unknown>;
  };
  const data = record(source);
  const definitions = data.variants ? Object.entries(record(data.variants)) : [["default", data]] as const;
  const variants: ThemeVariantSummary[] = definitions.map(([variantId, definition]) => {
    const variant = record(definition);
    const dark = record(variant.dark);
    const typing = record(dark.typing);
    const swatches = [record(dark.bg).base, typing.cursor, record(record(dark.interactive).secondary).DEFAULT, typing.correct];
    if (!swatches.every((color) => typeof color === "string")) throw new Error(`Invalid theme swatches: ${id}`);
    return {
      id: variantId,
      label: typeof variant.label === "string" ? variant.label : formatThemeName(variantId),
      light: variant.light != null,
      swatches: swatches as ThemeVariantSummary["swatches"],
    };
  });
  const defaultVariant = variants.find((variant) => variant.id === data.defaultVariant) ?? variants[0];
  if (!defaultVariant) throw new Error(`Theme has no variants: ${id}`);
  return {
    id,
    name: formatThemeName(id),
    category: typeof data.category === "string" && Object.hasOwn(CATEGORY_CONFIG, data.category)
      ? data.category as ThemeCategory : "default",
    defaultVariantId: defaultVariant.id,
    variants,
  };
}
